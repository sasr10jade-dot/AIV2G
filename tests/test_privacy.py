def test_consent_grant_withdraw_history_kept():
    assert not consent.has_consent("EV-1", "collect")
    consent.grant("EV-1", "collect", "v1")
    consent.grant("EV-1", "collect", "v1")  # 중복 등록은 행을 늘리지 않음
    assert consent.has_consent("EV-1", "collect") and not consent.has_consent("EV-1", "share_external")
    assert consent.withdraw("EV-1", "collect") is True
    assert not consent.has_consent("EV-1", "collect")
    assert consent.withdraw("EV-1", "collect") is False
    rows = consent.list_consents("EV-1")
    assert len(rows) == 1 and rows[0]["withdrawn_at"]  # 이력은 남는다
    with pytest.raises(ValueError):
        consent.grant("EV-1", "bogus", "v1")


def test_audit_chain_detects_tampering():
    for i in range(3):
        audit.log("tester", "act", target=f"t{i}", detail={"i": i})
    assert audit.verify_chain() == {"ok": True, "rows": 3, "broken_at": None}
    con = sqlite3.connect(consent.PRIVACY_DB)
    con.execute("UPDATE audit_log SET target='forged' WHERE id=2")
    con.commit()
    con.close()
    res = audit.verify_chain()
    assert res["ok"] is False and res["broken_at"] == 2


