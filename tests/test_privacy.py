def test_pseudo_id_is_stable_distinct_and_hides_value(monkeypatch):
    monkeypatch.setenv("PSEUDO_KEY", "k1")
    a = ps.pseudo_id("plate", "43오3450")
    assert a == ps.pseudo_id("plate", "43오3450") and a.startswith("PV-") and "3450" not in a
    assert a != ps.pseudo_id("plate", "43오3451")
    assert ps.pseudo_id("ev", "43오3450") != a  # 종류가 다르면 다른 가명
    monkeypatch.setenv("PSEUDO_KEY", "k2")
    assert ps.pseudo_id("plate", "43오3450") != a  # 키 교체 시 단절


def test_pseudo_key_file_autogenerated_when_no_env(monkeypatch):
    monkeypatch.delenv("PSEUDO_KEY", raising=False)
    first = ps.pseudo_id("ev", "EV-1")
    assert ps.KEY_FILE.exists() and ps.pseudo_id("ev", "EV-1") == first


